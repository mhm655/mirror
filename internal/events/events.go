// Package events defines MIRROR's event model.
//
// The single most important idea in this package is the split between
// COMMANDS and EFFECTS.
//
//	COMMAND  an input that the simulation could not have derived by itself:
//	         the operator injects an accident, a fork changes a policy, the
//	         population is seeded. Commands are the authoritative log. Replay
//	         means: start from the initial state implied by (mapParams, seed),
//	         apply commands at their recorded ticks, and step the engine.
//
//	EFFECT   an observation about something the simulation just did:
//	         a vehicle entered a road, a hospital hit capacity, a substation
//	         tripped. Effects are DERIVED. They are never replayed; they are
//	         regenerated identically by the same deterministic computation.
//
// Why this matters. Event-sourcing everything is the obvious move and it is
// wrong here. At 100k vehicles the engine produces on the order of 400k
// VehicleEnteredRoad effects per simulated minute. Persisting those as the
// system of record would mean writing ~2 GB/hour of data whose only purpose is
// to reconstruct something that a 30 MB checkpoint plus a few hundred commands
// reconstructs exactly. So:
//
//	system of record  = initial params + command log (tiny, append-only)
//	fast recovery     = checkpoint + commands since the checkpoint
//	observability     = effect stream, retained on a short ring buffer,
//	                    sampled into Postgres/Loki, never load-bearing
//
// See docs/architecture/event-model.md and docs/adr/ADR-006-event-sourcing.md.
