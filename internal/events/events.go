// Event is a fixed-size record.
//
// Four int64 payload slots instead of a map or an interface: an effect stream
// at 400k events/minute cannot afford an allocation per event, and a fixed
// layout means the whole ring buffer is one contiguous array that the
// WebSocket encoder can walk without touching the heap. The meaning of A..D is
// per-Kind and documented in payload.go.
type Event struct {
	Seq        uint64
	Tick       units.Tick
	Kind       Kind
	Severity   Severity
	Region     int16
	A, B, C, D int64
}

// Log is an append-only sequence of commands. This is the system of record.
//
// It is deliberately a plain slice with a monotonic sequence number rather than
// anything cleverer: the write rate is a few hundred entries per simulated
// hour, and the reader (replay) always wants the whole thing in order. Kafka,
// or even a b-tree, would be pure ceremony at this volume.
type Log struct {
	Cmds []Event
	next uint64
}

// Append inserts a command, keeping the log ordered by (Tick, Seq).
//
// Insertion rather than a plain append, because commands can be SCHEDULED for
// a future tick: an operator sets up a storm at 08:30 and then injects an
// accident for right now. A plain append leaves the log unsorted, and At()
// -- which assumes order -- silently stops finding commands. That failure is
// invisible (no error, the command just never happens) which makes it exactly
// the kind of bug worth designing out rather than documenting around.
//
// Seq is assigned before insertion, so it remains a global submission order and
// two commands scheduled for the same tick execute in the order they were
// submitted.
func (l *Log) Append(e Event) Event {
	if !e.Kind.IsCommand() {
		panic("events: only commands belong in the authoritative log")
	}
	e.Seq = l.next
	l.next++
	i := len(l.Cmds)
	for i > 0 && l.Cmds[i-1].Tick > e.Tick {
		i--
	}
	l.Cmds = append(l.Cmds, Event{})
	copy(l.Cmds[i+1:], l.Cmds[i:])
	l.Cmds[i] = e
	return e
}

// Ordered reports whether the log satisfies the (Tick, Seq) invariant that
// At() and Since() depend on. Exercised by TestLogOrdering.
func (l *Log) Ordered() bool {
	for i := 1; i < len(l.Cmds); i++ {
		if l.Cmds[i-1].Tick > l.Cmds[i].Tick {
			return false
		}
	}
	return true
}

func (l *Log) Len() int     { return len(l.Cmds) }
func (l *Log) Next() uint64 { return l.next }

// Since returns commands with Tick >= from, which is what a checkpoint-based
// recovery needs.
func (l *Log) Since(from units.Tick) []Event {
	i := 0
	for i < len(l.Cmds) && l.Cmds[i].Tick < from {
		i++
	}
	return l.Cmds[i:]
}

// At returns the commands scheduled exactly at a tick. Commands are appended in
// (tick, seq) order by construction, so this is a contiguous window.
func (l *Log) At(t units.Tick) []Event {
	lo := 0
	for lo < len(l.Cmds) && l.Cmds[lo].Tick < t {
		lo++
	}
	hi := lo
	for hi < len(l.Cmds) && l.Cmds[hi].Tick == t {
		hi++
	}
	return l.Cmds[lo:hi]
}

// Clone copies the entire log, including commands scheduled in the future.
//
// This is the right default for a counterfactual fork. "Simulation B is A with
// adaptive signals" means the two runs share not only their history but their
// entire scripted future -- the same accident at the same tick, the same storm
// at the same tick. If a fork silently dropped pending commands, a comparison
// between A and B would be measuring the difference in their event streams as
// much as the difference in their policies, which is exactly the confound a
// counterfactual is supposed to eliminate.
//
// Dropping a scheduled command is a separate, explicit act: see Fork.
func (l *Log) Clone() *Log {
	n := &Log{Cmds: make([]Event, len(l.Cmds)), next: l.next}
	copy(n.Cmds, l.Cmds)
	return n
}

// Fork copies commands up to and including branchTick, deliberately discarding
// anything scheduled after it. Use this when a scenario should keep the
// parent's history but write its own future.
func (l *Log) Fork(branchTick units.Tick) *Log {
	n := &Log{}
	for _, c := range l.Cmds {
		if c.Tick <= branchTick {
			n.Cmds = append(n.Cmds, c)
		}
	}
	n.next = l.next
	return n
}

// Ring is a bounded buffer of effect events for live streaming and for the
// "what just happened" panel.
//
// Bounded on purpose. Effects are not the system of record, so dropping the
// oldest ones under pressure is correct behaviour, not data loss -- and it
// means a slow WebSocket client can never apply backpressure to the simulation
// loop. That property is worth more than complete effect history.
type Ring struct {
	buf     []Event
	head    uint64 // total pushed
	dropped uint64
}

func NewRing(capacity int) *Ring {
	if capacity < 16 {
		capacity = 16
	}
	// Round up to a power of two so index math is a mask.
	c := 16
	for c < capacity {
		c <<= 1
	}
	return &Ring{buf: make([]Event, c)}
}

func (r *Ring) Push(e Event) {
	e.Seq = r.head
	r.buf[r.head&uint64(len(r.buf)-1)] = e
	r.head++
	if r.head > uint64(len(r.buf)) {
		r.dropped = r.head - uint64(len(r.buf))
	}
}

func (r *Ring) Head() uint64    { return r.head }
func (r *Ring) Dropped() uint64 { return r.dropped }
func (r *Ring) Cap() int        { return len(r.buf) }

// ReadFrom copies events with sequence >= from into out, oldest first, and
// returns the sequence the caller should ask for next. If the caller has fallen
// too far behind, it is fast-forwarded and told how many it missed.
func (r *Ring) ReadFrom(from uint64, out []Event, limit int) ([]Event, uint64, uint64) {
	out = out[:0]
	oldest := uint64(0)
	if r.head > uint64(len(r.buf)) {
		oldest = r.head - uint64(len(r.buf))
	}
	var missed uint64
	if from < oldest {
		missed = oldest - from
		from = oldest
	}
	n := 0
	for s := from; s < r.head && n < limit; s++ {
		out = append(out, r.buf[s&uint64(len(r.buf)-1)])
		n++
		from = s + 1
	}
	return out, from, missed
}
