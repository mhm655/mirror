func (k Kind) String() string {
	if n, ok := kindName[k]; ok {
		return n
	}
	return fmt.Sprintf("kind(%d)", uint16(k))
}

func (k Kind) IsCommand() bool { return k > CmdNone && k < cmdMax }
func (k Kind) IsEffect() bool  { return k >= EffectBase && k < evtMax }

